-- Text-to-SQL Evaluation System - Initial Schema Migration
-- This migration creates all tables for storing gold queries and evaluation metrics

-- Enable UUID extension if not already enabled
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- Table: gold_queries
-- Stores reference SQL queries that serve as the gold standard for evaluation
CREATE TABLE gold_queries (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  chat_input TEXT NOT NULL,
  session_id VARCHAR(255),
  member_id VARCHAR(255),
  clasificacion VARCHAR(100),
  pregunta_descompuesta TEXT,
  tablas_columnas_ddl TEXT NOT NULL,
  sql_reference TEXT NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Table: evaluations
-- Stores each evaluation instance linking a gold query to a generated SQL query
CREATE TABLE evaluations (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  gold_query_id UUID NOT NULL REFERENCES gold_queries(id) ON DELETE CASCADE,
  generated_sql TEXT NOT NULL,
  evaluation_date TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Table: execution_accuracy
-- Stores Execution Accuracy (EX) metric data for each evaluation
CREATE TABLE execution_accuracy (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  evaluation_id UUID NOT NULL REFERENCES evaluations(id) ON DELETE CASCADE,
  results_match BOOLEAN,
  is_correct BOOLEAN NOT NULL,
  evaluator_notes TEXT,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Table: time_to_answer
-- Stores Time-to-Answer (TTA) metric data for each evaluation
CREATE TABLE time_to_answer (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  evaluation_id UUID NOT NULL REFERENCES evaluations(id) ON DELETE CASCADE,
  start_time TIMESTAMP WITH TIME ZONE NOT NULL,
  end_time TIMESTAMP WITH TIME ZONE NOT NULL,
  duration_seconds NUMERIC(10, 2) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  CONSTRAINT valid_time_range CHECK (end_time > start_time),
  CONSTRAINT valid_duration CHECK (duration_seconds >= 0)
);

-- Table: component_matching
-- Stores Component Matching metric data evaluating individual SQL components
CREATE TABLE component_matching (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  evaluation_id UUID NOT NULL REFERENCES evaluations(id) ON DELETE CASCADE,
  select_correct BOOLEAN NOT NULL,
  where_correct BOOLEAN NOT NULL,
  group_by_correct BOOLEAN NOT NULL,
  order_by_correct BOOLEAN NOT NULL,
  keywords_correct BOOLEAN NOT NULL,
  f1_score NUMERIC(5, 4),
  evaluator_notes TEXT,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  CONSTRAINT valid_f1_score CHECK (f1_score IS NULL OR (f1_score >= 0 AND f1_score <= 1))
);

-- Indexes for performance optimization
-- Primary lookup indexes
CREATE INDEX idx_gold_queries_id ON gold_queries(id);
CREATE INDEX idx_evaluations_gold_query_id ON evaluations(gold_query_id);
CREATE INDEX idx_evaluations_evaluation_date ON evaluations(evaluation_date);

-- Foreign key indexes for join performance
CREATE INDEX idx_execution_accuracy_evaluation_id ON execution_accuracy(evaluation_id);
CREATE INDEX idx_time_to_answer_evaluation_id ON time_to_answer(evaluation_id);
CREATE INDEX idx_component_matching_evaluation_id ON component_matching(evaluation_id);

-- Additional indexes for common queries
CREATE INDEX idx_gold_queries_created_at ON gold_queries(created_at);
CREATE INDEX idx_evaluations_created_at ON evaluations(created_at);
CREATE INDEX idx_execution_accuracy_is_correct ON execution_accuracy(is_correct);

-- Comments for documentation
COMMENT ON TABLE gold_queries IS 'Reference SQL queries serving as gold standard for evaluation';
COMMENT ON TABLE evaluations IS 'Evaluation instances linking gold queries to generated SQL';
COMMENT ON TABLE execution_accuracy IS 'Execution Accuracy (EX) metric: percentage of queries with correct results';
COMMENT ON TABLE time_to_answer IS 'Time-to-Answer (TTA) metric: time taken to generate and evaluate queries';
COMMENT ON TABLE component_matching IS 'Component Matching metric: granular evaluation of SQL components with F1 scores';

COMMENT ON COLUMN gold_queries.chat_input IS 'Natural language input from user';
COMMENT ON COLUMN gold_queries.tablas_columnas_ddl IS 'DDL schema information for database context';
COMMENT ON COLUMN gold_queries.sql_reference IS 'Correct SQL query (gold standard)';
COMMENT ON COLUMN evaluations.generated_sql IS 'SQL query generated by the AI model';
COMMENT ON COLUMN execution_accuracy.is_correct IS 'Whether the generated query produces correct results';
COMMENT ON COLUMN time_to_answer.duration_seconds IS 'Time in seconds from start to completion';
COMMENT ON COLUMN component_matching.f1_score IS 'F1 score calculated from component matching precision and recall';
