# **Feature: text-to-sql-evaluation, Property 9: Timestamp recording**

# Strategy for generating valid UUIDs
valid_uuid_strategy = st.builds(uuid4)

# Strategy for generating valid timestamps with timezone
def valid_timestamp_strategy():
    """Generate valid timestamps with timezone"""
    return st.datetimes(
        min_value=datetime(2020, 1, 1),
        max_value=datetime(2030, 12, 31)
    ).map(lambda dt: dt.replace(tzinfo=timezone.utc))

# Strategy for generating valid SQL strings
valid_sql_strategy = st.text(min_size=10, max_size=200).filter(
    lambda x: x.strip() and not x.isspace()
)


class EvaluationService:
    """Simple evaluation service for testing timestamp recording without repository dependency"""
    
    def start_evaluation(self, gold_query_id: UUID, generated_sql: str) -> tuple[UUID, datetime]:
        """
        Start an evaluation and record the start timestamp.
        
        Args:
            gold_query_id: ID of the gold query being evaluated
            generated_sql: SQL generated by the AI model
            
        Returns:
            tuple: (evaluation_id, start_time)
        """
        evaluation_id = uuid4()
        start_time = datetime.now(timezone.utc)
        
        # In a real implementation, this would create the evaluation record
        # and the initial time_to_answer record with start_time
        
        return evaluation_id, start_time
    
    def complete_evaluation(self, evaluation_id: UUID, start_time: datetime) -> datetime:
        """
        Complete an evaluation and record the end timestamp.
        
        Args:
            evaluation_id: ID of the evaluation being completed
            start_time: When the evaluation was started
            
        Returns:
            datetime: end_time timestamp
        """
        end_time = datetime.now(timezone.utc)
        
        # Ensure end_time is after start_time
        if end_time <= start_time:
            # In testing, we might have very fast operations or future start_time, so add a small buffer
            end_time = start_time + timedelta(seconds=1)
        
        # In a real implementation, this would update the time_to_answer record
        # with end_time and calculate duration_seconds
        
        return end_time
    
    def create_time_to_answer_record(self, evaluation_id: UUID, start_time: datetime, end_time: datetime) -> TimeToAnswer:
        """
        Create a complete TimeToAnswer record with both timestamps.
        
        Args:
            evaluation_id: ID of the evaluation
            start_time: When evaluation started
            end_time: When evaluation completed
            
        Returns:
            TimeToAnswer: Complete record with timestamps and calculated duration
        """
        duration_seconds = (end_time - start_time).total_seconds()
        
        return TimeToAnswer(
            id=uuid4(),
            evaluation_id=evaluation_id,
            start_time=start_time,
            end_time=end_time,
            duration_seconds=duration_seconds,
            created_at=datetime.now(timezone.utc)
        )


