"""Evaluation model for linking gold queries to generated SQL"""

from pydantic import BaseModel, Field
from datetime import datetime
from uuid import UUID
from typing import Optional

from .execution_accuracy import ExecutionAccuracyCreate
from .time_to_answer import TimeToAnswerCreate
from .component_matching import ComponentMatchingCreate


class Evaluation(BaseModel):
    """Model for evaluation instances linking gold queries to generated SQL"""
    
    id: UUID
    gold_query_id: UUID = Field(..., description="Reference to the gold query being evaluated")
    generated_sql: str = Field(..., min_length=1, description="SQL query generated by the AI model")
    evaluation_date: datetime
    created_at: datetime

    class Config:
        from_attributes = True
        json_encoders = {
            datetime: lambda v: v.isoformat(),
            UUID: lambda v: str(v)
        }


class EvaluationCreate(BaseModel):
    """Model for creating new evaluations"""
    
    gold_query_id: UUID = Field(..., description="Reference to the gold query being evaluated")
    generated_sql: str = Field(..., min_length=1, description="SQL query generated by the AI model")

    class Config:
        from_attributes = True


class ExecutionAccuracyData(BaseModel):
    """Execution accuracy data for complete evaluation creation"""
    results_match: Optional[bool] = Field(None, description="Whether query results match")
    is_correct: bool = Field(..., description="Whether the generated query produces correct results")
    evaluator_notes: Optional[str] = None


class TimeToAnswerData(BaseModel):
    """Time to answer data for complete evaluation creation"""
    start_time: datetime = Field(..., description="Timestamp when evaluation started")
    end_time: datetime = Field(..., description="Timestamp when evaluation completed")
    duration_seconds: float = Field(..., ge=0, description="Time in seconds from start to completion")


class ComponentMatchingData(BaseModel):
    """Component matching data for complete evaluation creation"""
    select_correct: bool = Field(..., description="Whether SELECT component is correct")
    where_correct: bool = Field(..., description="Whether WHERE component is correct")
    group_by_correct: bool = Field(..., description="Whether GROUP BY component is correct")
    order_by_correct: bool = Field(..., description="Whether ORDER BY component is correct")
    keywords_correct: bool = Field(..., description="Whether KEYWORDS component is correct")
    f1_score: Optional[float] = Field(None, ge=0.0, le=1.0, description="F1 score calculated from component matching")
    evaluator_notes: Optional[str] = None


class CompleteEvaluationCreate(BaseModel):
    """Model for creating complete evaluations with all related metrics"""
    
    gold_query_id: UUID = Field(..., description="Reference to the gold query being evaluated")
    generated_sql: str = Field(..., min_length=1, description="SQL query generated by the AI model")
    execution_accuracy: ExecutionAccuracyData = Field(..., description="Execution accuracy metrics")
    time_to_answer: TimeToAnswerData = Field(..., description="Time to answer metrics")
    component_matching: ComponentMatchingData = Field(..., description="Component matching metrics")

    class Config:
        from_attributes = True